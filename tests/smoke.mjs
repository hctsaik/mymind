import { chromium } from 'playwright-core';
const exe=process.env.HOME+'/.cache/ms-playwright/chromium-1255/chrome-linux64/chrome';
const BASE=process.env.BASE||'http://localhost:8765/';
const b=await chromium.launch({executablePath:exe});
const p=await b.newPage({viewport:{width:1440,height:900}}); const errs=[]; p.on('pageerror',e=>errs.push(e.message)); p.on('console',m=>{if(m.type()==='error')errs.push('console: '+m.text())});
await p.goto(BASE); await p.waitForSelector('body[data-ready="1"]');
console.log('welcome:', await p.locator('.welcome h1').textContent());
await p.click('[data-act="welcomeLocal"]'); await p.waitForTimeout(200);
console.log('empty:', await p.locator('.empty h3').textContent());
await p.click('.empty [data-act="new"]'); await p.waitForTimeout(400);
await p.keyboard.type('我的測試圖'); await p.keyboard.press('Enter'); await p.waitForTimeout(200);
console.log('title:', await p.locator('#maptitle').textContent());
await p.keyboard.press('Tab'); await p.keyboard.type('子節點A'); await p.keyboard.press('Enter');
await p.keyboard.press('Enter'); await p.keyboard.type('同級B'); await p.keyboard.press('Enter');
console.log('nodes:', await p.locator('#mapsvg g.node').count(), await p.evaluate(()=>window.__mm.doc.root.c.map(c=>c.t+':'+(c.c||[]).map(x=>x.t).join(','))));
await p.keyboard.press('Control+z'); console.log('after undo:', await p.locator('#mapsvg g.node').count());
await p.keyboard.press('Control+y'); console.log('after redo:', await p.locator('#mapsvg g.node').count());
await p.screenshot({path:'/tmp/mm/app1.png'});
console.log('errors:',errs);
await b.close();
